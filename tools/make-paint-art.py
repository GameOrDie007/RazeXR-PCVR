#!/usr/bin/env python3
"""
Generate the Paintball splats, plus the .def that turns them into tiles.

    python tools/make-paint-art.py

Writes wadsrc/static/vrpaint/*.png and wadsrc/static/engine/vr_paint.def, which
the build packs into raze.pk3. Our own art, drawn here from noise; the output is
the same every run.

MODERN   modern00..23: wet paint, four splat shapes in six bright colors, each a
         round blob with drips and spots and a soft highlight.
CLASSIC  classic00..15: one splat shape, its four corners each a random pure
         color (each channel full or none) blended across it. A sprite takes
         one color for the whole thing, so the blends are baked in.

Tiles (vr_paintball.cpp must agree):
    30600 + n    modern n, n = 0..23
    30630 + n    classic n, n = 0..15

Copyright (C) 2026 RazeXR PCVR port. GPL-2.0-or-later, see gpl-2.0.txt.
"""
import math
import os
import random

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "wadsrc", "static", "vrpaint")
DEF = os.path.join(REPO, "wadsrc", "static", "engine", "vr_paint.def")

SIZE = 128
MODERN_TILE = 30600
CLASSIC_TILE = 30630

MODERN_COLORS = [
    (235, 30, 40), (255, 150, 0), (250, 225, 20),
    (40, 200, 60), (30, 110, 255), (220, 40, 210),
]
PURE = [(r * 255, g * 255, b * 255) for r in (0, 1) for g in (0, 1) for b in (0, 1)]


def splat_mask(seed):
    """Coverage 0..1 per pixel: a lumpy blob, drips running out from it and
    loose spots, with a soft one-pixel edge."""
    rnd = random.Random(seed)
    c = SIZE / 2.0
    r0 = SIZE * 0.24
    waves = [(rnd.randint(3, 9), rnd.uniform(0, 2 * math.pi), rnd.uniform(0.05, 0.16)) for _ in range(5)]
    drips = []
    for _ in range(rnd.randint(4, 7)):
        drips.append((rnd.uniform(0, 2 * math.pi), rnd.uniform(0.30, 0.46) * SIZE, rnd.uniform(2.0, 4.5)))
    spots = []
    for _ in range(rnd.randint(6, 12)):
        ang = rnd.uniform(0, 2 * math.pi)
        d = rnd.uniform(0.30, 0.46) * SIZE
        spots.append((c + math.cos(ang) * d, c + math.sin(ang) * d, rnd.uniform(1.5, 4.5)))
    m = [[0.0] * SIZE for _ in range(SIZE)]
    for y in range(SIZE):
        for x in range(SIZE):
            dx, dy = x + 0.5 - c, y + 0.5 - c
            r = math.hypot(dx, dy)
            th = math.atan2(dy, dx)
            v = r0 * (1.0 + sum(a * math.sin(k * th + p) for k, p, a in waves)) - r
            for ang, length, wid in drips:
                ux, uy = math.cos(ang), math.sin(ang)
                t = dx * ux + dy * uy
                if 0.0 < t < length:
                    side = abs(-dx * uy + dy * ux)
                    v = max(v, wid * (1.0 - 0.6 * t / length) - side)
                    v = max(v, wid * 0.9 - math.hypot(dx - ux * length, dy - uy * length))
            for sx, sy, sr in spots:
                v = max(v, sr - math.hypot(x + 0.5 - sx, y + 0.5 - sy))
            m[y][x] = max(0.0, min(1.0, v + 0.5))
    return m


def save(name, pixel):
    """pixel(x, y) -> (r, g, b, a) floats 0..1. Fully see-through pixels take
    the splat's own color, so filtering never pulls a dark fringe in."""
    img = Image.new("RGBA", (SIZE, SIZE))
    px = img.load()
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, a = pixel(x, y)
            px[x, y] = (int(r * 255 + 0.5), int(g * 255 + 0.5), int(b * 255 + 0.5), int(a * 255 + 0.5))
    img.save(os.path.join(OUT, name + ".png"))


def modern(shape, color):
    m = splat_mask(1000 + shape)
    c = SIZE / 2.0

    def pixel(x, y):
        a = m[y][x]
        hx, hy = (x - c * 0.75) / SIZE, (y - c * 0.75) / SIZE
        shine = max(0.0, 0.35 - math.hypot(hx, hy) * 1.6)
        k = 0.86 + 0.14 * a + shine
        return tuple(min(1.0, color[i] / 255.0 * k + shine * 0.5) for i in range(3)) + (a,)
    return pixel


def classic(seed):
    rnd = random.Random(5000 + seed)
    corners = [rnd.choice(PURE) for _ in range(4)]
    while len(set(corners)) < 2:
        corners = [rnd.choice(PURE) for _ in range(4)]
    m = splat_mask(777)

    def pixel(x, y):
        u, v = x / (SIZE - 1.0), y / (SIZE - 1.0)
        col = [((1 - u) * (1 - v) * corners[0][i] + u * (1 - v) * corners[1][i]
                + (1 - u) * v * corners[2][i] + u * v * corners[3][i]) / 255.0 for i in range(3)]
        return (col[0], col[1], col[2], m[y][x])
    return pixel


def main():
    os.makedirs(OUT, exist_ok=True)
    lines = ["// Generated by tools/make-paint-art.py - do not edit by hand.",
             "// Paintball (VR Options > Hands and Weapons): the splats a shot leaves on a wall."]
    n = 0
    for shape in range(4):
        for ci, col in enumerate(MODERN_COLORS):
            k = shape * len(MODERN_COLORS) + ci
            name = "modern%02d" % k
            save(name, modern(shape, col))
            lines.append('tilefromtexture %d { file "vrpaint/%s.png" }' % (MODERN_TILE + k, name))
            n += 1
    for k in range(16):
        name = "classic%02d" % k
        save(name, classic(k))
        lines.append('tilefromtexture %d { file "vrpaint/%s.png" }' % (CLASSIC_TILE + k, name))
        n += 1
    with open(DEF, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %d splats to %s" % (n, OUT))


if __name__ == "__main__":
    main()
