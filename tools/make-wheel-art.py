#!/usr/bin/env python3
"""
Generate the weapon wheel's disc art: one pie wedge per slice count, plain and
lit in each game's colour, plus the .def that turns them into tiles.

    python tools/make-wheel-art.py

Writes wadsrc/static/vrwheel/*.png and wadsrc/static/engine/vr_wheel.def, which
the build packs into raze.pk3. Our own art, drawn here from geometry; re-run it
after changing a colour or a size.

Each wedge points straight up, centred on the image: the renderer turns it into
place (HWSprite, vr_wheel tiles only). Pointing up keeps it symmetric left to
right, so it comes out right however the sprite's texture is mapped across.

Tiles (vr_wheel.cpp must agree):
    30400 + n            plain wedge for a wheel of n slices, n = 1..12
    30420 + 16*c + n     lit wedge, colour c (see COLOURS)

Copyright (C) 2026 RazeXR PCVR port. GPL-2.0-or-later, see gpl-2.0.txt.
"""
import math
import os

from PIL import Image, ImageDraw

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "wadsrc", "static", "vrwheel")
DEF = os.path.join(REPO, "wadsrc", "static", "engine", "vr_wheel.def")

SIZE = 256          # final image, pixels
SS = 4              # supersampling for smooth edges
INNER = 0.22        # hub hole, as a fraction of the radius
GAP_DEG = 1.2       # half the dark gap between slices

PLAIN = (24, 24, 28, 200)
RIM = (90, 90, 96, 230)
# One per game family; vr_wheel.cpp picks by game.
COLOURS = [
    ("duke",    (255, 200, 0, 235)),     # Duke Nukem 3D: yellow
    ("redneck", (230, 120, 30, 235)),    # Redneck Rampage: orange
    ("nam",     (150, 170, 60, 235)),    # NAM, WWII GI: olive
    ("blood",   (200, 20, 25, 235)),     # Blood: blood red
    ("sw",      (30, 170, 95, 235)),     # Shadow Warrior: jade
    ("exhumed", (40, 120, 210, 235)),    # PowerSlave / Exhumed: lapis
]

PLAIN_BASE = 30400
LIT_BASE = 30420


def wedge(n, fill, rim):
    s = SIZE * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c = s / 2.0
    r_out = c * 0.98
    r_in = c * INNER
    half = 180.0 / n
    gap = GAP_DEG if n > 1 else 0.0
    # Screen angles: 0 = up, clockwise; PIL's 0 is right, also clockwise.
    a0 = -90.0 - half + gap
    a1 = -90.0 + half - gap
    steps = max(8, int((a1 - a0) / 1.0))

    def ring(r, a_from, a_to):
        pts = []
        for k in range(steps + 1):
            a = math.radians(a_from + (a_to - a_from) * k / steps)
            pts.append((c + r * math.cos(a), c + r * math.sin(a)))
        return pts

    if n == 1:
        d.ellipse([c - r_out, c - r_out, c + r_out, c + r_out], fill=fill)
        d.ellipse([c - r_in, c - r_in, c + r_in, c + r_in], fill=(0, 0, 0, 0))
    else:
        poly = ring(r_out, a0, a1) + list(reversed(ring(r_in, a0, a1)))
        d.polygon(poly, fill=fill)
    # A thin rim on the outer edge, so the disc reads against a busy level.
    rim_w = max(2, int(s * 0.012))
    for k in range(rim_w):
        r = r_out - k
        if n == 1:
            d.ellipse([c - r, c - r, c + r, c + r], outline=rim)
        else:
            d.line(ring(r, a0, a1), fill=rim, width=1)
    return img.resize((SIZE, SIZE), Image.LANCZOS)


def main():
    os.makedirs(OUT, exist_ok=True)
    lines = [
        "// Generated by tools/make-wheel-art.py - do not edit by hand.",
        "// The weapon wheel's disc: a wedge per slice count, plain and lit.",
    ]
    for n in range(1, 13):
        name = "wedge%02d.png" % n
        wedge(n, PLAIN, RIM).save(os.path.join(OUT, name))
        lines.append('tilefromtexture %d { file "vrwheel/%s" }' % (PLAIN_BASE + n, name))
    for ci, (cname, col) in enumerate(COLOURS):
        rim = tuple(min(255, int(v * 1.15)) for v in col[:3]) + (255,)
        for n in range(1, 13):
            name = "wedge%02d_%s.png" % (n, cname)
            wedge(n, col, rim).save(os.path.join(OUT, name))
            lines.append('tilefromtexture %d { file "vrwheel/%s" }' % (LIT_BASE + 16 * ci + n, name))
    with open(DEF, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", 12 * (1 + len(COLOURS)), "wedges and", DEF)


if __name__ == "__main__":
    main()
